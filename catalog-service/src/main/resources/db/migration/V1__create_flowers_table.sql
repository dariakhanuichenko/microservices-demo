CREATE TABLE flowers
(
    id         UUID PRIMARY KEY,
    name       VARCHAR(100)   NOT NULL,
    price      NUMERIC(12, 2) NOT NULL,
    updated_at TIMESTAMP      NOT NULL,
    CONSTRAINT chk_flowers_price CHECK (price >= 0)
);

